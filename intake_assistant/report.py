"""Render assessments as markdown intake briefs and portfolio summaries."""
from __future__ import annotations

from typing import List

from .models import Assessment
from .phi_guard import redact


def _bar(score: int) -> str:
    return "●" * score + "○" * (5 - score)


def intake_brief(a: Assessment) -> str:
    uc = a.use_case
    lines = [
        f"# AI Opportunity Intake Brief: {uc.title}",
        "",
        f"**Business area:** {uc.business_area}  ",
        f"**Workflow domain:** {a.workflow_domain}  ",
        f"**AI patterns:** {', '.join(a.ai_patterns)}  ",
        f"**Sponsor:** {uc.sponsor or 'TBD'}  ",
        f"**Priority score:** {a.priority_score}/100 — **{a.quadrant}**",
        "",
        "## Use case summary",
        a.use_case_summary,
        "",
        "## Business value hypothesis",
        a.value_hypothesis,
        "",
        f"Estimated capacity released: **~{a.estimated_hours_saved_per_month:,.0f} hrs/month "
        f"(~{a.estimated_fte_equivalent} FTE)** — planning estimate, validate against baseline.",
        "",
        "## Initial solution concept",
        a.solution_concept,
        "",
        "## Assessment scorecard",
        "| Dimension | Score | Rationale |",
        "|---|---|---|",
    ]
    for s in a.scores:
        label = "Risk (higher = riskier)" if s.name == "Risk" else s.name
        lines.append(f"| {label} | {_bar(s.score)} {s.score}/5 | {s.rationale} |")
    lines += ["", "## Draft requirements"] + [f"- {r}" for r in a.requirements]
    lines += ["", "## Success metrics"] + [f"- {m}" for m in a.success_metrics]
    lines += ["", "## Responsible AI review", "| Category | Severity | Finding | Mitigation | Escalate |", "|---|---|---|---|---|"]
    for f in a.responsible_ai_flags:
        lines.append(f"| {f.category} | {f.severity} | {f.finding} | {f.mitigation} | {'Yes' if f.escalate else 'No'} |")
    lines += ["", "## Open questions for next discovery session"] + [f"- [ ] {q}" for q in a.open_questions]
    lines += ["", f"<sub>Narrative generated by: {a.generated_by}. Scores are rule-based and reproducible.</sub>", ""]
    return redact("\n".join(lines)).text


def portfolio_table(results: List[Assessment]) -> str:
    lines = [
        "# AI Opportunity Portfolio — Prioritized",
        "",
        "| Rank | Opportunity | Domain | Priority | Quadrant | Hrs/mo | Value | Feas. | Data | Risk | Escalate |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for i, a in enumerate(results, 1):
        esc = "⚠️" if any(f.escalate for f in a.responsible_ai_flags) else ""
        lines.append(
            f"| {i} | {a.use_case.title} | {a.workflow_domain} | {a.priority_score} | {a.quadrant} | "
            f"{a.estimated_hours_saved_per_month:,.0f} | {a.score('Business Value')} | {a.score('Feasibility')} | "
            f"{a.score('Data Readiness')} | {a.score('Risk')} | {esc} |"
        )
    total = sum(a.estimated_hours_saved_per_month for a in results)
    lines += ["", f"**Total estimated capacity:** ~{total:,.0f} hrs/month (~{total/160:.1f} FTE)", ""]
    return "\n".join(lines)
